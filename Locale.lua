local locale = type(GetLocale) == "function" and GetLocale() or "enUS"
local L = {}
for k, v in pairs(EN) do L[k] = v end
if locale == "deDE" then
    for k, v in pairs(DE) do L[k] = v end
end

OP.locale = locale
OP.L = L
function OP:T(key)
    return (self.L and self.L[key]) or key
end
